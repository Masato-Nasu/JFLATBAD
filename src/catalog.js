function normalize(value) {
  return value.normalize('NFKC').toLowerCase().trim();
}

function matchesFilter(entry, filter) {
  return filter === 'all' || (filter === 'rejected' ? entry.verdict === 'rejected' : entry.kind === filter);
}

function searchSamples(query, filter) {
  const terms = normalize(query).split(/\s+/).filter(Boolean);
  return CATALOG.filter((entry) => {
    if (!matchesFilter(entry, filter)) return false;
    const index = normalize([entry.title, entry.subject, entry.number, entry.abstract].join(' '));
    return terms.every((term) => index.includes(term));
  }).slice(0, 8);
}

function shuffled(entries) {
  const copy = [...entries];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function randomSamples(filter) {
  const pool = shuffled(CATALOG.filter((entry) => matchesFilter(entry, filter)));
  if (filter === 'rejected') return pool.slice(0, 8);
  const rejected = pool.filter((entry) => entry.verdict === 'rejected');
  const accepted = pool.filter((entry) => entry.verdict === 'approved');
  const recognized = filter === 'all'
    ? [...accepted.filter((entry) => entry.kind === 'patent').slice(0, 4),
        ...accepted.filter((entry) => entry.kind === 'model').slice(0, 3)]
    : accepted.slice(0, 7);
  return shuffled([...recognized, ...rejected.slice(0, 8 - recognized.length)]);
}

function maybeIncludeSpecial(records, filter) {
  if (records.length < 8 || !matchesFilter(SELF, filter) || Math.random() >= 0.01) return records;
  const match = records.findLastIndex((entry) => entry.verdict === 'approved' && entry.kind === SELF.kind);
  return match < 0 ? records : records.map((entry, index) => index === match ? SELF : entry);
}
