function placedSymbol(name, x, y) {
  const symbol = PART_SYMBOLS.find(([pattern]) => pattern.test(name))?.[1] ?? DEFAULT_PART_SYMBOL;
  const offset = [x - 46, y - 36];
  let axis = 0;
  return symbol.split(' ').map((token) => {
    if (/^[A-Z]$/.test(token)) {
      axis = 0;
      return token;
    }
    const value = Number(token) + offset[axis];
    axis = 1 - axis;
    return value;
  }).join(' ');
}

